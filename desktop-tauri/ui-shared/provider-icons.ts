// 只使用网关已校验的缓存文件，不让插件元数据变成浏览器的任意外链请求。
export function cachedPluginIconPath(value: unknown): string {
  return typeof value === 'string' && /^\/plugins\/script-icons\/[a-f0-9]{64}\.(png|jpg|gif|webp|ico|svg)$/.test(value) ? value : ''
}

export function cachedProviderIconPath(icons: unknown, provider: string): string {
  if (!provider || !icons || typeof icons !== 'object' || Array.isArray(icons)) return ''
  return cachedPluginIconPath((icons as Record<string, unknown>)[provider])
}
